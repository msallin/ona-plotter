// OnaPlotter SignalK plugin shim (deployed alongside the webapp
// bundle). The package.json carries both the `signalk-webapp` and
// `signalk-node-server-plugin` keywords:
//
//   * signalk-webapp:           mounts public/ at /<package-name>/
//                               via express.static.
//   * signalk-node-server-plugin: loads this file as a plugin so we
//                               can register additional routes.
//
// The webapp half serves static files; Blazor WASM uses
// client-side routing, so deep URLs like /signalk-onaplotter/map
// or /signalk-onaplotter/settings don't map to any file and
// return 404 on reload. The plugin half adds an SPA fallback:
// any GET under /<package-name>/ that the static mount didn't
// handle falls through to this route and we return public/index.html
// so the Blazor router takes over in the browser.
//
// Registration order: signalk-server's webapp interface mounts
// express.static BEFORE it starts plugins, so real static files
// still win and only genuine "no such file" misses reach this
// fallback. The regex excludes paths containing a '.' so a
// missing .wasm / .css / .js still returns a proper 404 instead
// of pretending to be HTML.
//
// The plugin also registers POST /log as a client-side error sink.
// Blazor's "An unhandled error has occurred" banner is opaque on
// iPad, and SSH-tailing the SignalK server log is the practical
// debug path at the helm - so the Blazor host installs window
// error listeners that POST to this endpoint. We forward each
// payload through app.error() so the entry appears in the
// standard SignalK log (journalctl -u signalk / /var/log/signalk).
// Throttled on the client to 1 Hz; the server-side is stateless.
//
// Finally the plugin serves precompressed .br / .gz siblings for
// _framework/, js/, css/ and lib/. express.static only ever sends the
// identity bytes, so without this a cold load pulls the full-size WASM
// runtime, assemblies and scripts over the boat's wifi. _framework/
// siblings come from the SDK (fingerprinted, never rewritten after
// publish); js/, css/ and lib/ siblings are regenerated by the Release
// publish after minifying and bundling (scripts/precompress.mjs), so
// they match the bytes on disk. index.html (base href patched at
// staging), service-worker.js and appsettings.json are not negotiated:
// they change after the SDK compressed them.
//
// signalk-server calls start() on every enable and settings save and
// stop() on disable, but Express can't remove a route. Routes are
// therefore registered once per app and fall through (next()) while
// the plugin is stopped.

const path = require('path');
const fs = require('fs');

/** Precompressed sibling suffix per Content-Encoding, in preference order. */
const ENCODING_SUFFIX = { br: '.br', gzip: '.gz' };
const ENCODING_PREFERENCE = ['br', 'gzip'];

const CONTENT_TYPES = {
    '.wasm': 'application/wasm',
    '.js': 'text/javascript; charset=utf-8',
    '.mjs': 'text/javascript; charset=utf-8',
    '.json': 'application/json; charset=utf-8',
    '.css': 'text/css; charset=utf-8',
    '.html': 'text/html; charset=utf-8',
};

/**
 * Encodings from ENCODING_PREFERENCE the client accepts, best first:
 * higher q wins, ties keep br before gzip. A wildcard covers any
 * encoding the header does not name.
 *   "gzip, deflate, br"        -> ['br', 'gzip']
 *   "gzip;q=1.0, br;q=0.5"     -> ['gzip', 'br']
 *   "br;q=0, *"                -> ['gzip']
 *   "" / undefined / "identity" -> []
 */
function acceptableEncodings(acceptEncoding) {
    const q = new Map();
    for (const part of String(acceptEncoding || '').split(',')) {
        const [rawName, ...params] = part.trim().split(';');
        const name = rawName.trim().toLowerCase();
        if (!name) continue;
        let weight = 1;
        for (const p of params) {
            const m = /^\s*q\s*=\s*([0-9.]+)\s*$/i.exec(p);
            if (m) weight = Number(m[1]);
        }
        if (Number.isFinite(weight)) q.set(name, weight);
    }
    const wildcard = q.has('*') ? q.get('*') : 0;
    return ENCODING_PREFERENCE
        .map((enc, order) => ({ enc, order, weight: q.has(enc) ? q.get(enc) : wildcard }))
        .filter((e) => e.weight > 0)
        .sort((a, b) => b.weight - a.weight || a.order - b.order)
        .map((e) => e.enc);
}

/** Content-Type for the uncompressed file the client asked for. */
function contentTypeFor(filePath) {
    return CONTENT_TYPES[path.extname(filePath).toLowerCase()] || 'application/octet-stream';
}

/**
 * Map a request path relative to the _framework mount onto a file
 * inside frameworkDir, or null when it is malformed or escapes it.
 *   "/dotnet.native.8f1c.wasm" -> "<frameworkDir>/dotnet.native.8f1c.wasm"
 *   "/../index.html"           -> "<frameworkDir>/index.html" (clamped to the root)
 *   "/..%5C..%5Cindex.html"    -> null on Windows (backslash escape)
 */
function resolveFrameworkFile(frameworkDir, relPath) {
    let decoded;
    try { decoded = decodeURIComponent(relPath || ''); }
    catch { return null; }
    if (!decoded || decoded.includes('\0') || decoded.endsWith('/')) return null;
    const root = path.resolve(frameworkDir);
    const full = path.resolve(root, '.' + path.posix.normalize('/' + decoded));
    return full.startsWith(root + path.sep) ? full : null;
}

/**
 * Express middleware for the _framework mount: when the client accepts
 * br or gzip and a precompressed sibling exists, send it with the
 * original Content-Type plus Content-Encoding; otherwise fall through
 * to express.static. Vary is set either way so a shared cache never
 * hands br bytes to a client that did not ask for them.
 */
function createPrecompressedMiddleware(frameworkDir, exists = fs.existsSync) {
    return function onaPrecompressed(req, res, next) {
        if (req.method !== 'GET' && req.method !== 'HEAD') return next();
        const file = resolveFrameworkFile(frameworkDir, req.path);
        if (!file || !exists(file)) return next();
        res.append('Vary', 'Accept-Encoding');
        for (const enc of acceptableEncodings(req.headers['accept-encoding'])) {
            const compressed = file + ENCODING_SUFFIX[enc];
            if (!exists(compressed)) continue;
            res.setHeader('Content-Encoding', enc);
            res.setHeader('Content-Type', contentTypeFor(file));
            return res.sendFile(compressed, (err) => {
                if (!err || res.headersSent) return;
                res.removeHeader('Content-Encoding');
                res.removeHeader('Content-Type');
                next();
            });
        }
        return next();
    };
}

/**
 * Register middleware on mountPath so it runs BEFORE the webapp's
 * express.static layer for the same path. signalk-server mounts webapp
 * statics before it starts plugins, so a plain app.use would only ever
 * see requests static had already answered. Moves our layer directly in
 * front of the matching serveStatic layer (keeping any earlier auth
 * middleware ahead of both). Returns false and leaves the layer where
 * app.use put it when the router internals are not recognised; identity
 * serving then continues unchanged.
 */
function useBeforeStatic(app, mountPath, middleware, probePath) {
    app.use(mountPath, middleware);
    const router = app._router || app.router;
    const stack = router && router.stack;
    if (!Array.isArray(stack)) return false;
    const oursIdx = stack.findIndex((l) => l && l.handle === middleware);
    if (oursIdx < 0) return false;
    const staticIdx = stack.findIndex((l, i) => i !== oursIdx && l && l.name === 'serveStatic'
        && typeof l.match === 'function' && l.match(probePath));
    if (staticIdx < 0 || staticIdx > oursIdx) return staticIdx > oursIdx;
    const [ours] = stack.splice(oursIdx, 1);
    stack.splice(staticIdx, 0, ours);
    return true;
}

/** Static directories under public/ served with precompressed siblings. */
const PRECOMPRESSED_DIRS = ['_framework', 'js', 'css', 'lib'];

/** Per-app registration state, shared by every plugin instance on it. */
const appStates = new WeakMap();

function stateFor(app) {
    let state = appStates.get(app);
    if (!state) {
        state = { running: false, registered: false };
        appStates.set(app, state);
    }
    return state;
}

/** Wraps an Express handler so it only acts while the plugin runs. */
function whileRunning(state, handler) {
    return function onaWhileRunning(req, res, next) {
        if (!state.running) return next();
        return handler(req, res, next);
    };
}

module.exports = function (app) {
    return createPlugin(app, __dirname);
};

/**
 * Builds the plugin object. baseDir holds public/ (the deployed webapp
 * bundle); its folder name is the package name, so the shim stays
 * portable across scoped / renamed installs.
 */
function createPlugin(app, baseDir) {
    const PACKAGE_NAME = path.basename(baseDir);
    const INDEX_HTML = path.join(baseDir, 'public', 'index.html');
    const ROUTE_PREFIX = '/' + PACKAGE_NAME;
    const state = stateFor(app);

    const plugin = {
        id: PACKAGE_NAME,
        name: 'OnaPlotter (SPA fallback)',
        description:
            'Serves public/index.html for any Blazor client-routed path under ' +
            ROUTE_PREFIX + ' so reload / direct link / back button return the ' +
            'app instead of a bare 404.',

        schema: () => ({ type: 'object', properties: {} }),

        start: () => {
            if (!fs.existsSync(INDEX_HTML)) {
                state.running = false;
                app.setPluginError(
                    'public/index.html missing; SPA fallback disabled'
                );
                return;
            }
            state.running = true;
            if (!state.registered) {
                registerRoutes();
                state.registered = true;
            }
            app.setPluginStatus(
                'SPA fallback, error relay and br/gzip static serving registered at ' +
                ROUTE_PREFIX + '/*'
            );
        },

        stop: () => {
            state.running = false;
            app.setPluginStatus('Stopped');
        },
    };

    function registerRoutes() {
        // Error relay: POST /<pkg>/log. Accepts JSON bodies of the
        // shape { message, stack?, url?, userAgent?, ts? } and
        // forwards to the SignalK server log. We cap the payload
        // size so a misbehaving client can't flood the log with
        // a minified stack the size of the world.
        //
        // SignalK's webapp HTTP surface already applies the admin
        // auth middleware before our handlers run, so only an
        // authenticated user can reach this endpoint. No CORS
        // needed because the Blazor client is same-origin.
        const MAX_BYTES = 8 * 1024;
        app.post(ROUTE_PREFIX + '/log', whileRunning(state, (req, res) => {
            try {
                const body = req.body || {};
                const message = String(body.message || 'no message').slice(0, 800);
                const stack   = String(body.stack   || '').slice(0, MAX_BYTES);
                const url     = String(body.url     || '').slice(0, 400);
                const ua      = String(body.userAgent || '').slice(0, 200);
                const ts      = String(body.ts      || new Date().toISOString());
                app.error(
                    '[onaplotter] client-error ' + ts + ' ' + ua + ' | ' +
                    message + (stack ? ' | ' + stack : '') +
                    (url ? ' | at ' + url : '')
                );
                res.json({ ok: true });
            } catch (e) {
                res.status(400).json({ ok: false, error: String(e) });
            }
        }));

        for (const dir of PRECOMPRESSED_DIRS) {
            const mount = ROUTE_PREFIX + '/' + dir;
            const ahead = useBeforeStatic(app, mount,
                whileRunning(state, createPrecompressedMiddleware(
                    path.join(baseDir, 'public', dir))),
                mount + '/probe.js');
            if (!ahead) {
                app.debug('precompressed ' + dir + '/ serving registered behind ' +
                    'express.static; clients receive identity-encoded files');
            }
        }

        // Match any GET under the webapp prefix that doesn't
        // contain a '.' (i.e. not a file extension). Real assets
        // like /<pkg>/_framework/foo.wasm keep flowing through
        // express.static; only client routes (/<pkg>/map etc.)
        // land here.
        const fallback = new RegExp('^' + ROUTE_PREFIX + '/[^.]+$');
        app.get(fallback, whileRunning(state, (req, res) => {
            res.sendFile(INDEX_HTML);
        }));
    }

    return plugin;
}

// Exposed for deploy/index.test.js; signalk-server only calls the factory.
module.exports.internals = {
    createPlugin,
    acceptableEncodings,
    contentTypeFor,
    resolveFrameworkFile,
    createPrecompressedMiddleware,
    useBeforeStatic,
};
